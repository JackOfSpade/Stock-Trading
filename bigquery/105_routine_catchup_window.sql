-- state.go_without_order -- D3 catch-up-window redefinition (owner directive 2026-07-25).
-- SUPERSEDES the state.go_without_order view definition in bigquery/18_stack_review_fixes.sql (D3 --
-- staging-completeness surface, RUNBOOK §25). Every column, join, and the two NOT EXISTS blocks below
-- are copied byte-for-byte from that original definition -- the ONLY change is the window predicate
-- that bounds `go_decisions.entry_date`.
--
-- ORIGINAL BEHAVIOUR (bigquery/18): a fixed `entry_date >= DATE_SUB(CURRENT_DATE('America/Denver'),
-- INTERVAL 2 DAY)` lookback (~36h in Claude_Task_Plan.md's D3 prose -- see that file's GO-WITHOUT-ORDER
-- self-check bullet). That fixed window meant a GO logged while D3 itself was down for multiple days
-- (e.g. the 2026-07-23/24 connector outage) could age out of the window before D3 ever ran again to
-- review it -- a genuine go_without_order candidate silently missed forever, not just delayed.
--
-- NEW BEHAVIOUR: the window is now GREATEST(2 days, days since D3's own last completed ops.run_log
-- run) -- FLOORED at the original ~36h/2-day lookback (it never narrows below what bigquery/18 always
-- used), and WIDENS automatically when D3 has been down longer than that, so a GO logged during any gap
-- in D3's own run history is still in-window the next time D3 (or a catch-up run standing in for it)
-- actually executes and reads this view. D3 having never logged a completed run at all falls back to
-- the original 2-day floor (COALESCE), not full history. D3 has no known legacy non-ASCII routine-id
-- form in ops.run_log (unlike AR_att/AR_orc), so a plain `routine = 'D3'` equality match is sufficient
-- here -- the RUNBOOK §28 id-separator normalization used elsewhere in this file is not needed.
--
-- DECISIONS STAY CURRENT-SESSION-SCOPED: this view only widens the EVIDENCE this routine reads: which
-- historical GO rows D3 reviews for a missing staged order. It does not retroactively place, alter, or
-- backdate any order -- D3's own adjudication step (Claude_Task_Plan.md) still runs fresh, in the
-- current session, against whatever this view surfaces.
--
-- DO NOT re-apply bigquery/18's original CREATE statement for this object live in isolation -- it would
-- revert the window to the fixed 2-day cutoff and silently reintroduce the missed-catch-up gap this
-- redefinition exists to close. bigquery/18's copy is kept there, unmodified, for DR-rebuild
-- apply-in-order reference only (see the SUPERSEDED marker added there pointing at this file).
CREATE OR REPLACE VIEW `stock-trading-498512.state.go_without_order` AS
WITH d3_last_completed AS (
  -- D3's own last completed ops.run_log run -- the anchor for how far back this view's evidence window
  -- needs to reach.
  SELECT MAX(log_ts) AS d3_last_completed_ts
  FROM `stock-trading-498512.ops.run_log`
  WHERE routine = 'D3' AND status = 'completed'
),
go_decisions AS (
  SELECT entry_id, entry_date, strategy, ticker, entry_type, title
  FROM `stock-trading-498512.events.decision_log`
  WHERE decision = 'GO'
    AND superseded_by IS NULL
    AND entry_date >= DATE_SUB(
      CURRENT_DATE('America/Denver'),
      -- FLOORED at the original fixed 2-day (~36h) lookback (GREATEST semantics): never narrower than
      -- bigquery/18's original definition, but widens to D3's own last-completion gap when that is
      -- bigger -- see the file-level comment above this CREATE statement.
      INTERVAL (
        SELECT GREATEST(
          2,
          COALESCE(
            DATE_DIFF(CURRENT_DATE('America/Denver'), DATE(d3_last_completed_ts, 'America/Denver'), DAY),
            2
          )
        )
        FROM d3_last_completed
      ) DAY
    )
)
SELECT
  g.entry_id, g.entry_date, g.strategy, g.ticker, g.entry_type, g.title,
  CURRENT_TIMESTAMP() AS checked_at
FROM go_decisions g
-- no staged order references this decision (by ref, else by ticker+strategy on/after the decision day).
-- DATE(..., 'America/Denver') — NOT the bare (UTC-default) form — because g.entry_date is the
-- Denver OPERATING day decision_log stamps; a bare UTC date is always >= the Denver date, so an
-- order/fill actually staged the PRIOR Denver evening (>=~17:00 MT = already the next UTC day) could
-- wrongly satisfy this match and suppress a genuine go-without-order candidate (false negative only;
-- 2026-07 report-system fix).
WHERE NOT EXISTS (
  SELECT 1 FROM `stock-trading-498512.events.queue_events` q
  WHERE q.queue = 'ORDER_STAGED'
    AND (JSON_VALUE(q.payload, '$.source_decision_ref') = g.entry_id
         OR (q.ticker = g.ticker AND q.strategy = g.strategy AND DATE(q.event_ts, 'America/Denver') >= g.entry_date))
)
-- and no fill recorded for that strategy/ticker on/after the decision day
AND NOT EXISTS (
  SELECT 1 FROM `stock-trading-498512.events.trade_fills` f
  WHERE f.ticker = g.ticker AND f.strategy = g.strategy
    AND DATE(f.fill_ts, 'America/Denver') >= g.entry_date
);

