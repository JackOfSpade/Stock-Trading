-- Per-routine catch-up analysis window (owner directive 2026-07-25, in response to the 2026-07-23/24
-- connector outage: missed days were never covered because each routine's next run only looked at
-- "today"/its own fixed lookback). Project: stock-trading-498512. Apply after bigquery/10_observability.sql
-- (ops.run_log) and bigquery/18_stack_review_fixes.sql (state.go_without_order, redefined below) -- no
-- other dependency; deliberately does NOT read state.cadence_watch / state.cadence_period_watch /
-- state.catchup_available so it can never inherit their same-day/same-period/catchup-safe scoping
-- limits (see header note below).
--
-- WHY THIS EXISTS. Every existing cadence view answers "did routine X miss its CURRENT slot" (state.
-- cadence_watch: today; state.cadence_period_watch: this week/month/quarter/year; state.trigger_
-- attestation: a coarse multi-period overdue threshold) and their alarms are DECOUPLED from what a
-- routine actually reads when it runs -- verified 2026-07-23/24: a 2-day connector outage meant D1..D3/
-- AR_att/AR_orc/W4/W5/etc. simply lost that day's evidence forever once their fixed lookback window
-- rolled forward, even though ops.alerts' missed_run rows for those days had themselves already silently
-- auto-resolved by aging out (see ops.sp_auto_resolve_alerts Rule 2, bigquery/34_alert_lifecycle.sql --
-- resolves on EITHER a later completion OR simply on the alert turning >1 day stale, whichever comes
-- first -- so "the alert cleared" is never proof the missed window was actually analyzed).
--
-- THIS VIEW answers a different, decision-agnostic question for every routine unconditionally, every
-- time it runs: "as of right now, how far back does my OWN evidence/analysis window need to reach?"
-- window_start_ts = the timestamp of my own last completed run, or (if I have never completed) a
-- cadence-sized fallback. DECISIONS made during the run stay current-session-scoped (nobody retroactively
-- places an order) -- only the EVIDENCE window widens. A routine's own Task_Plan preamble step reads its
-- one row here at start and folds window_start_ts into whatever it queries (Daily.md scan range, decision_
-- log lookback, etc.) -- wiring that read-and-fold-in step into Claude_Task_Plan.md's preamble and into
-- each routine's fixed-window prose is a SEPARATE follow-up, not part of this file. BEST-EFFORT / NON-
-- GATING by design (mirrors the OPS0 "must never be blocked" rule): a routine that cannot read this view
-- (BigQuery unreachable, view missing) falls back to its own existing cadence-default lookback and notes
-- that it did so -- it must never fail or halt on this view's absence.
--
-- BLINDING IS UNCHANGED. This view only widens HOW FAR BACK IN TIME a routine's evidence window reaches
-- -- it says nothing about, and never restricts, WHICH sources a routine may read (AR_att's strict
-- blinding, M1a's file-boundary blinding, etc. are untouched).
--
-- ROUTINE LIST: ops/cadence.yaml's `routines:` block (32 ids) is the sole source of truth. No existing
-- BigQuery object carries {routine, monitor_class} for all 31 including the 4 queue_driven ids (AR_att/
-- AR_orc/SL2/SL5) -- bigquery/12's and bigquery/24's UNNEST lists both deliberately EXCLUDE queue_driven
-- (not calendar-predictable), and bigquery/15's ops.routine_catalog has all 32 ids but no monitor_class
-- column at all. So the `routines` CTE below is GENERATED by scripts/gen_routine_lists.py (--write) from
-- ops/cadence.yaml, a 4th marker region alongside its existing bigquery/12/15/24 regions -- do NOT
-- hand-edit the STRUCT rows between the BEGIN/END GENERATED ROUTINE LIST markers; edit ops/cadence.yaml
-- and re-run `python scripts/gen_routine_lists.py --write` instead. `python scripts/gen_routine_lists.py
-- --check` (CI-gating) fails the build if this region drifts from ops/cadence.yaml.
--
-- FALLBACK WINDOW (cadence-default, used only when a routine has NEVER logged a completed run): daily
-- classes (daily_trading/daily_all) -> 1 day; weekly_sun -> 7 days; monthly_ftd -> 31 days; quarterly_ftd
-- -> 92 days; annual_ftd -> 366 days. queue_driven (AR_att/AR_orc/SL2/SL5) is NOT one of the schema's
-- named calendar classes -- it is a DELIBERATE, called-out design choice here to give it the same 1-day
-- fallback as the daily tier, matching its "checked daily, fires only if due" cadence (ops/cadence.yaml:
-- AR_att/AR_orc/SL2/SL5 all have `schedule: "daily; if ... due<=today"`). This is NOT dictated by any
-- existing spec and should be confirmed, not assumed, before this view is treated as final.
--
-- ID-SEPARATOR NORMALIZATION: joins on REGEXP_REPLACE(routine, r'[·._-]', ''), the same normalization
-- state.instruction_drift uses (bigquery/15_routine_catalog.sql, RUNBOOK §28), so legacy AR·att/AR·orc
-- middle-dot rows (2026-06-20..07-02 in ops.run_log) fold onto the current ASCII AR_att/AR_orc keys
-- instead of being silently dropped from the MAX(log_ts) computation.
--
-- SYNTHETIC-ROW SAFETY: the routines CTE is a closed, generated list -- NOT `SELECT DISTINCT routine
-- FROM ops.run_log` -- specifically so synthetic markers written by fire-drill/self-heal procedures
-- (FIRE_DRILL_ORDER_GUARD, FIRE_DRILL_ALERT_LATCH, FIRE_DRILL_ALERT_RESOLVE, FIRE_DRILL_DEP,
-- FIRE_DRILL_DEP_CONSUMER, SELFHEAL_RUN_LOG -- all confirmed live in ops.run_log) never appear as phantom
-- "routines" with their own (meaningless) catch-up windows.
--
-- TIMEZONE: deliberately NOT wrapped in DATETIME(..., 'America/Denver') anywhere -- unlike state.cadence_
-- watch's wall-clock 21:00 MT DEADLINE GUARD, this view has no deadline semantics at all, just a rolling
-- elapsed-time lookback from CURRENT_TIMESTAMP() (a UTC instant), so there is no DST edge to get wrong.
--
-- NO CAP on window_days: a routine that silently broke for months before finally completing again would
-- get an arbitrarily large window here (bounded only by its own run_log history). Not addressed by the
-- 2026-07-25 directive as scoped; a future safety valve (e.g. cap at N x its own cadence default) is a
-- design call for whoever wires this into the routines' actual evidence-gathering steps, not assumed here.
CREATE OR REPLACE VIEW `stock-trading-498512.state.routine_catchup_window` AS
WITH routines AS (
  -- GENERATED (scripts/gen_routine_lists.py --write, from ops/cadence.yaml, file order), ALL 32 ids
  -- incl. the 4 queue_driven ones. Do NOT hand-edit -- see header note above.
  SELECT * FROM UNNEST([
    -- BEGIN GENERATED ROUTINE LIST (scripts/gen_routine_lists.py --write; do not hand-edit)
    STRUCT('D1' AS routine, 'daily_trading' AS monitor_class),
    STRUCT('D2a' AS routine, 'daily_trading' AS monitor_class),
    STRUCT('D2' AS routine, 'daily_trading' AS monitor_class),
    STRUCT('D3' AS routine, 'daily_all' AS monitor_class),
    STRUCT('OPS0' AS routine, 'daily_all' AS monitor_class),
    STRUCT('OPS1' AS routine, 'daily_all' AS monitor_class),
    STRUCT('OPS2' AS routine, 'daily_all' AS monitor_class),
    STRUCT('SL3' AS routine, 'daily_trading' AS monitor_class),
    STRUCT('AR_att' AS routine, 'queue_driven' AS monitor_class),
    STRUCT('AR_orc' AS routine, 'queue_driven' AS monitor_class),
    STRUCT('SL2' AS routine, 'queue_driven' AS monitor_class),
    STRUCT('SL5' AS routine, 'queue_driven' AS monitor_class),
    STRUCT('W1' AS routine, 'weekly_sun' AS monitor_class),
    STRUCT('W2' AS routine, 'weekly_sun' AS monitor_class),
    STRUCT('W3' AS routine, 'weekly_sun' AS monitor_class),
    STRUCT('W4' AS routine, 'weekly_sun' AS monitor_class),
    STRUCT('W5' AS routine, 'weekly_sun' AS monitor_class),
    STRUCT('M1a' AS routine, 'monthly_ftd' AS monitor_class),
    STRUCT('M1b' AS routine, 'monthly_ftd' AS monitor_class),
    STRUCT('M2' AS routine, 'monthly_ftd' AS monitor_class),
    STRUCT('M3' AS routine, 'monthly_ftd' AS monitor_class),
    STRUCT('M4' AS routine, 'monthly_ftd' AS monitor_class),
    STRUCT('M5' AS routine, 'monthly_ftd' AS monitor_class),
    STRUCT('SL4' AS routine, 'monthly_ftd' AS monitor_class),
    STRUCT('Q1' AS routine, 'quarterly_ftd' AS monitor_class),
    STRUCT('Q2' AS routine, 'quarterly_ftd' AS monitor_class),
    STRUCT('Q3' AS routine, 'quarterly_ftd' AS monitor_class),
    STRUCT('Q4' AS routine, 'quarterly_ftd' AS monitor_class),
    STRUCT('SL1' AS routine, 'quarterly_ftd' AS monitor_class),
    STRUCT('A1' AS routine, 'annual_ftd' AS monitor_class),
    STRUCT('A2' AS routine, 'annual_ftd' AS monitor_class),
    STRUCT('A3' AS routine, 'annual_ftd' AS monitor_class)
  -- END GENERATED ROUTINE LIST
  ])
),
last_completed AS (
  -- Latest 'completed' log_ts per routine, id-separator-normalized (RUNBOOK §28 convention) so legacy
  -- AR·att/AR·orc middle-dot rows fold onto the current AR_att/AR_orc keys instead of being invisible.
  SELECT
    REGEXP_REPLACE(routine, r'[·._-]', '') AS routine_norm,
    MAX(log_ts) AS last_completed_ts
  FROM `stock-trading-498512.ops.run_log`
  WHERE status = 'completed'
  GROUP BY routine_norm
),
joined AS (
  SELECT
    r.routine,
    r.monitor_class,
    lc.last_completed_ts,
    lc.last_completed_ts IS NULL AS never_completed,
    -- Cadence-default fallback, in whole days -- used only when never_completed. queue_driven's fallback
    -- (1 day) is a design choice, not a named class in the brief -- see header note.
    CASE r.monitor_class
      WHEN 'daily_trading' THEN 1
      WHEN 'daily_all'     THEN 1
      WHEN 'weekly_sun'    THEN 7
      WHEN 'monthly_ftd'   THEN 31
      WHEN 'quarterly_ftd' THEN 92
      WHEN 'annual_ftd'    THEN 366
      WHEN 'queue_driven'  THEN 1
      ELSE 31   -- defensive: an unrecognized class should never occur (routines CTE is closed/generated)
    END AS fallback_days
  FROM routines r
  LEFT JOIN last_completed lc
    ON lc.routine_norm = REGEXP_REPLACE(r.routine, r'[·._-]', '')
)
SELECT
  routine,
  monitor_class,
  last_completed_ts,
  never_completed,
  fallback_days,
  -- The raw cadence-default fallback instant (always computed, for transparency/debugging), independent
  -- of whether it actually gets used below.
  TIMESTAMP_SUB(CURRENT_TIMESTAMP(), INTERVAL fallback_days DAY) AS cadence_fallback_window_start_ts,
  -- The window every routine actually reads: its own last completion, or the cadence fallback if it has
  -- never completed.
  COALESCE(
    last_completed_ts,
    TIMESTAMP_SUB(CURRENT_TIMESTAMP(), INTERVAL fallback_days DAY)
  ) AS window_start_ts,
  -- Elapsed size of that window in (fractional) days, for quick human/dashboard reading.
  ROUND(
    TIMESTAMP_DIFF(
      CURRENT_TIMESTAMP(),
      COALESCE(last_completed_ts, TIMESTAMP_SUB(CURRENT_TIMESTAMP(), INTERVAL fallback_days DAY)),
      MINUTE
    ) / 1440.0, 2
  ) AS window_days,
  CURRENT_TIMESTAMP() AS checked_at
FROM joined
ORDER BY routine;

