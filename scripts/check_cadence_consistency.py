def check_depends_on(cad):
    """Error strings for any depends_on entry that is not a known routine id in cad (a dangling/typo'd
    dependency -- it feeds the FATAL ops.sp_assert_deps gate, so a silent typo here would abort a live
    routine at runtime instead of failing this offline check), PLUS any depends_on CYCLE -- a direct
    self-reference or an indirect/mutual chain across two or more routines (2026-09-02,
    'depends-on-no-cycle-check' finding). Every depends_on chain in ops/cadence.yaml today is acyclic,
    so this was dormant, not a live bug -- but sp_assert_deps can never be satisfied for a routine
    caught in a cycle (each participant's precondition depends on the other's, which can never
    complete first), so a future edit that introduces one -- directly, or indirectly across two edits
    each individually passing the dangling-id check above -- would silently deadlock every participant
    every single day with no other CI signal."""
    errors = []
    for rid, r in cad.items():
        for dep in (r.get("depends_on") or []):
            if dep not in cad:
                errors.append(f"{rid}: depends_on '{dep}' is not a routine id in ops/cadence.yaml "
                              f"(dangling/typo'd dependency — it feeds the FATAL sp_assert_deps gate)")

    # Cycle detection: DFS from each routine over the depends_on graph (KNOWN ids only -- a dangling
    # dep is already reported above and is treated as a dead end here, never a cycle edge). "start is
    # reachable from itself in >=1 hop" catches BOTH shapes with no special-casing needed: a DIRECT
    # self-reference (depends_on: [X] on X itself) is the 1-hop case, and an INDIRECT/mutual cycle
    # across any number of routines is the same check at a longer hop count.
    for start in sorted(cad):
        # Reset PER start, not shared across the outer loop: a cycle A->B->A discovered while
        # start="A" and the SAME cycle discovered while start="B" have the same sorted-node-set key
        # ({A, B}) but must each still produce their own error line (one per participating routine,
        # per the finding's own spec) -- sharing this set across starts would suppress the second one
        # as a spurious "duplicate".
        reported_cycles = set()
        stack = [(start, (start,))]
        while stack:
            node, path = stack.pop()
            for dep in (cad.get(node, {}).get("depends_on") or []):
                if dep not in cad:
                    continue  # dangling -- already reported above, not this walk's job
                if dep == start:
                    # Found a cycle rooted at `start`. Key on the FULL set of routines it passes
                    # through (not the path tuple itself) so the same cycle discovered via two
                    # different DFS orderings from the same `start` is reported only once.
                    key = tuple(sorted(set(path)))
                    if key in reported_cycles:
                        continue
                    reported_cycles.add(key)
                    errors.append(
                        f"{start}: depends_on cycle detected: {' -> '.join((*path, start))} "
                        f"(feeds the FATAL sp_assert_deps gate — a self/mutual dependency can never "
                        f"be satisfied)")
                    continue
                if dep in path:
                    continue  # revisits a node already on THIS path without returning to `start` --
                              # a DIFFERENT cycle, not rooted here; it is caught when that node is
                              # itself walked as `start`, so descending further here would only loop
                stack.append((dep, (*path, dep)))
    return errors


def catchup_list_errors(cad, path, filename, tier_word, classes):
    """Check K for ONE of bigquery/31/59's hand-maintained catchup-safe `UNNEST([...]) AS routine`
    lists: it must equal cadence.yaml's {catchup_safe AND monitor_class in <classes>} subset.

    An ABSENT file is skipped silently (pre-feature checkout); a PRESENT-but-unparseable file FAILS
    loudly (DISARMED) so a benign SQL reformat can never silently disarm the guard. The daily
    (bigquery/31) and period (bigquery/59) call sites differ only in (path, filename, tier_word,
    classes), so this shared helper keeps their two error strings — the observable contract — from
    ever drifting apart with a one-sided edit. Returns a list of error strings (possibly empty)."""
    want = catchup_safe_want(cad, classes)  # shared with catchup_cte_list_errors + the yesterday tier
    have = parse_unnest_routine_ids(path)
    if have is None and os.path.exists(path):
        return [
            f"{filename} exists but no `UNNEST([...]) AS routine` bracket could be "
            f"parsed — check K's catchup-safe {tier_word} drift guard is DISARMED (regex rot? e.g. a "
            f"reformat to `AS  routine` or `UNNEST(ARRAY[...]`). Restore a parseable bracket."]
    if have is not None:
        have_set = set(have)
        if have_set != want:
            return [
                f"{filename} catchup-safe {tier_word} UNNEST list DRIFT — "
                f"file has {sorted(have_set)}, cadence.yaml-derived (catchup_safe AND {tier_word} tier) "
                f"wants {sorted(want)}"]
    return []


def catchup_safe_want(cad, classes):
    """cadence.yaml's {catchup_safe AND monitor_class in <classes>} routine-id subset — the single
    "want" derivation shared by catchup_list_errors() above, catchup_cte_list_errors() below and
    check K's yesterday-tier comparison in main(), so the three can never disagree about what the
    declared judgment call actually is."""
    return {rid for rid, r in cad.items()
            if r.get("catchup_safe") is True and r.get("monitor_class") in classes}


def catchup_cte_list_errors(cad, path, filename, tier_word, classes, cte_name):
    """Check K for a catchup-safe list reached BY CTE NAME rather than by position — the parser
    catchup_list_errors() above cannot use, because UNNEST_ROUTINE_BRACKET.search() only ever sees the
    FIRST bracket in the file it is pointed at (see CATCHUP_SAFE_CTE_RE's own comment). Used for the
    copies that are NOT their file's first bracket, or that live in a file check K never read at all:
    bigquery/90's period bracket, and both of bigquery/184's (the LIVE bodies of state.catchup_
    available / state.period_catchup_available).

    Same observable contract as catchup_list_errors(): an ABSENT file is skipped silently, a
    PRESENT-but-unparseable one FAILS loudly (DISARMED), and the DRIFT string keeps that function's
    wording token-for-token ("<file> catchup-safe <tier> UNNEST list DRIFT — file has [...],
    cadence.yaml-derived (catchup_safe AND <tier> tier) wants [...]") because CI and a BigQuery bridge
    parse these strings. Only the DISARMED text differs, and only to name the CTE that could not be
    found, which is the actual failure here.

    Returns a list of error strings (possibly empty) — one per occurrence of the named CTE that
    disagrees with cadence.yaml, so a file carrying two copies of the same list reports both."""
    want = catchup_safe_want(cad, classes)
    brackets = parse_catchup_safe_cte_ids(path, cte_name)
    if brackets is None and os.path.exists(path):
        return [
            f"{filename} exists but no `{cte_name} AS (SELECT routine FROM UNNEST([...]))` CTE could "
            f"be parsed — check K's catchup-safe {tier_word} drift guard is DISARMED for this copy "
            f"(regex rot? e.g. the CTE renamed, or a reformat to `UNNEST(ARRAY[...]`). Restore a "
            f"parseable CTE, or update CATCHUP_SAFE_CTE_RE in this script to match its new shape."]
    errs = []
    for i, ids in enumerate(brackets or []):
        have_set = set(ids)
        if have_set == want:
            continue
        # `filename` alone while there is exactly one copy (always, today) so the message is
        # byte-identical to catchup_list_errors()'s; disambiguated only if a file ever grows a second.
        where = filename if len(brackets) == 1 else f"{filename} (`{cte_name}` copy {i + 1})"
        errs.append(
            f"{where} catchup-safe {tier_word} UNNEST list DRIFT — "
            f"file has {sorted(have_set)}, cadence.yaml-derived (catchup_safe AND {tier_word} tier) "
            f"wants {sorted(want)}")
    return errs


