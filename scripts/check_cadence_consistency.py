def parse_period_grace_sql():
    """{monitor_class: grace_days} from bigquery/24_cadence_period_watch.sql.

    month/quarter/year are OFFSET N (0-indexed -> the (N+1)th trading day); weekly is a plain
    calendar-day count already expressed the same way period_grace_days.weekly_sun is (1 = Monday).
    Returns None if the file is absent (pre-2026-07-03 checkout) so the caller can skip check E.
    """
    if not os.path.exists(PERIOD_WATCH_SQL):
        return None
    txt = read_text(PERIOD_WATCH_SQL)
    out = {}
    for offset, which in PERIOD_GRACE_OFFSET.findall(txt):
        cls = {"month": "monthly_ftd", "quarter": "quarterly_ftd", "year": "annual_ftd"}[which]
        out[cls] = int(offset) + 1
    m = PERIOD_GRACE_WEEKLY.search(txt)
    if m:
        out["weekly_sun"] = int(m.group(1))
    return out


