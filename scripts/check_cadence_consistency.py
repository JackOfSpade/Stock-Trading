# PERF NOTE, THE FOUR FUNCTIONS BELOW (2026-08-31 code-quality pass, cadence#1): find_canonical_
# cadence_watch_file() and find_canonical_stalled_runs_file() each used to independently walk +
# strip_sql_comments() EVERY bigquery/*.sql file (already 205 and growing), even though BIGQUERY_DIR
# and STALLED_RUNS_BIGQUERY_DIR point at the SAME directory in production (see STALLED_RUNS_
# BIGQUERY_DIR's own comment near BIGQUERY_DIR) -- two full walks of one tree. Their matching
# parse_canonical_deadline_sql()/parse_stalled_runs_cls_ids() then each threw that work away and
# re-read + re-stripped the WINNING file a second time. Measured: find_canonical_cadence_watch_file()
# alone cost ~359ms; parse_canonical_deadline_sql() (which calls it, then redoes the winner) cost
# ~677ms; the check-O equivalent cost ~617ms -- roughly 1.3s of the script's ~2.26s total runtime came
# from re-walking/re-reading this one tree. All four now accept an optional `scan` -- a pre-computed
# _scan_bigquery_dir() result -- so main() can build ONE shared scan per run (see _scan_bigquery_dir's
# own docstring) and thread it through every one of them, instead of each function doing its own walk
# and its own extra re-read of the winner. Every direct/standalone call (as most of the test suite
# makes) omits `scan` and gets a fresh walk right here, exactly as before this pass.
def _scan_bigquery_dir(bigquery_dir):
    """[(number, path, stripped_text), ...] for every bigquery/NN_*.sql file in `bigquery_dir`, read
    and comment-stripped exactly once -- the shared walk find_canonical_cadence_watch_file() and
    find_canonical_stalled_runs_file() below both need. This is a plain function, not a persisted
    cache: it re-walks the directory on every call, so calling it fresh at the top of main() (or
    letting a callee do so when no `scan` is passed) can never see stale content from an earlier call
    in the same process -- the correctness property tests that monkeypatch BIGQUERY_DIR/
    STALLED_RUNS_BIGQUERY_DIR between calls rely on."""
    out = []
    for number, path in numbered_sql_files(bigquery_dir):
        if os.path.isdir(path):
            continue
        out.append((number, path, strip_sql_comments(read_text(path))))
    return out


