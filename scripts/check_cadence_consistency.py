def evening_slot_guard_membership_errors(cad):
    """FAIL LOUD if ops/cadence.yaml's actual evening-slot (expected_trigger.time_local >=
    EVENING_SLOT_THRESHOLD) routine population diverges from the union of EVENING_DAILY_GUARD_IDS and
    NOON_CLAUSE_EXEMPT_EVENING_IDS — see the comment block above NOON_CLAUSE_EXEMPT_EVENING_IDS for the
    full rationale. FOUR hard-error cases, the first three mirroring check_cron_dst_safety.py's
    daily_sun_thu_coverage_errors(): UNCLASSIFIED (evening-slot in cadence.yaml, in neither set — a
    new/re-timed routine nobody has decided about), STALE (named in one of the sets but no longer
    evening-slot in cadence.yaml), OVERLAP (named in both — a self-contradiction), and UNPLACEABLE
    (a DAILY-tier routine whose expected_trigger.time_local is missing or not "HH:MM", so it cannot
    be put on either side of EVENING_SLOT_THRESHOLD at all — see the branch's own comment)."""
    exempt_ids = set(NOON_CLAUSE_EXEMPT_EVENING_IDS)
    guard_ids = set(EVENING_DAILY_GUARD_IDS)
    errs = []

    overlap = guard_ids & exempt_ids
    if overlap:
        errs.append(
            f"scripts/check_cadence_consistency.py: {sorted(overlap)} appear in BOTH "
            f"EVENING_DAILY_GUARD_IDS and NOON_CLAUSE_EXEMPT_EVENING_IDS — pick one.")

    candidates = set()
    for rid, r in cad.items():
        tl = (r.get("expected_trigger") or {}).get("time_local")
        if isinstance(tl, str) and HHMM.match(tl) and tl >= EVENING_SLOT_THRESHOLD:
            candidates.add(rid)

    unclassified = candidates - (guard_ids | exempt_ids)
    if unclassified:
        errs.append(
            f"{sorted(unclassified)}: expected_trigger.time_local >= {EVENING_SLOT_THRESHOLD!r} in "
            f"ops/cadence.yaml (an evening-slot routine exposed to bigquery/12's midnight-crossing "
            f"mis-stamp) but named in NEITHER EVENING_DAILY_GUARD_IDS nor "
            f"NOON_CLAUSE_EXEMPT_EVENING_IDS in scripts/check_cadence_consistency.py. Add it to "
            f"EVENING_DAILY_GUARD_IDS (with a per-routine noon-clause SAME-DAY DOUBLE-RUN GUARD copy "
            f"in Claude_Task_Plan.md) or to NOON_CLAUSE_EXEMPT_EVENING_IDS with a one-line reason "
            f"before check M can validate it.")

    stale = (guard_ids | exempt_ids) - candidates
    if stale:
        errs.append(
            f"{sorted(stale)}: named in EVENING_DAILY_GUARD_IDS or NOON_CLAUSE_EXEMPT_EVENING_IDS in "
            f"scripts/check_cadence_consistency.py but no longer expected_trigger.time_local >= "
            f"{EVENING_SLOT_THRESHOLD!r} in ops/cadence.yaml (renamed, retired, or retimed) — remove "
            f"the stale entry.")

    # UNPLACEABLE (2026-09-04, 'cadence-evening-candidates-need-daily-time-local'). The candidate
    # derivation above reads expected_trigger.time_local, an OPTIONAL documentation field: no checker
    # REQUIRES it for a custom_cron routine (check I validates it only under `rec in ("daily",
    # "weekly")`, a branch no routine reaches today — all 32 are custom_cron — and
    # check_cron_dst_safety.py's check 3 is gated on `if tl:`), and 15 of the 32 live routines omit it
    # outright. So a routine with no time_local is not UNCLASSIFIED and not STALE: it silently drops
    # OUT of `candidates` and becomes invisible to check M entirely — the SAME fail-open drop-out
    # property the comment block above NOON_CLAUSE_EXEMPT_EVENING_IDS forbids for the guard-TEXT
    # source ("a routine missing its guard would simply drop OUT of the candidate set and this
    # cross-check would pass vacuously"). Making the derivation TOTAL closes it.
    #
    # SCOPED TO DAILY_CLASSES DELIBERATELY, and this scoping is the load-bearing part: the 15
    # routines that legitimately omit time_local are all period-tier or queue-driven (M1a M1b M2 M3 M4
    # M5 SL4 Q1 Q2 Q3 Q4 SL1 A1 A2 A3), and widening this to every routine would red-line CI on all of
    # them for a field they have no obligation to declare. Check M's per-id loop only ever covers the
    # daily cohort, so the daily cohort is exactly the population whose placement must be total. All 8
    # daily-tier routines carry a well-formed time_local today (D1 16:00, D2a 16:40, D2 17:15, D3
    # 18:45, SL3 20:00, OPS0 22:30, OPS1 06:30, OPS2 22:15), so this is a green no-op on the live file.
    #
    # The GATE is the same `isinstance(tl, str) and HHMM.match(tl)` test the candidate derivation
    # itself uses (HHMM is lib.textio's shared HHMM_RE — see its alias comment), so this branch fires
    # on exactly the values that derivation would drop; the MESSAGE delegates to
    # lib.textio.validate_hhmm_field so this does not become a fourth hand-copy of the base-60 wording
    # (2026-09-02 'hhmm-validation-triplicated' finding).
    for rid in sorted(cad):
        r = cad[rid] or {}
        if r.get("monitor_class") not in DAILY_CLASSES:
            continue
        tl = (r.get("expected_trigger") or {}).get("time_local")
        if isinstance(tl, str) and HHMM.match(tl):
            continue
        shape_err = validate_hhmm_field(tl, f"{rid}: expected_trigger.time_local")
        errs.append(
            f"{shape_err} — and {rid} is a "
            f"DAILY-tier routine (monitor_class={r.get('monitor_class')!r}), so without a parseable "
            f"time_local it can be placed on NEITHER side of the {EVENING_SLOT_THRESHOLD!r} "
            f"evening-slot threshold: it is not UNCLASSIFIED and not STALE, it is INVISIBLE to check "
            f"M's guard-text loop altogether. Declare expected_trigger.time_local in ops/cadence.yaml "
            f"(check_cron_dst_safety.py's check 3 then validates it against cron_utc).")
    return errs

