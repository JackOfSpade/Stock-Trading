def catchup_list_errors(cad, path, filename, tier_word, classes):
    """Check K for ONE of bigquery/31/59's hand-maintained catchup-safe `UNNEST([...]) AS routine`
    lists: it must equal cadence.yaml's {catchup_safe AND monitor_class in <classes>} subset.

    An ABSENT file is skipped silently (pre-feature checkout); a PRESENT-but-unparseable file FAILS
    loudly (DISARMED) so a benign SQL reformat can never silently disarm the guard. The daily
    (bigquery/31) and period (bigquery/59) call sites differ only in (path, filename, tier_word,
    classes), so this shared helper keeps their two error strings — the observable contract — from
    ever drifting apart with a one-sided edit. Returns a list of error strings (possibly empty)."""
    want = {rid for rid, r in cad.items()
            if r.get("catchup_safe") is True and r.get("monitor_class") in classes}
    have = parse_unnest_routine_ids(path)
    if have is None and os.path.exists(path):
        return [
            f"{filename} exists but no `UNNEST([...]) AS routine` bracket could be "
            f"parsed — check K's catchup-safe {tier_word} drift guard is DISARMED (regex rot? e.g. a "
            f"reformat to `AS  routine` or `UNNEST(ARRAY[...]`). Restore a parseable bracket."]
    if have is not None:
        have_set = set(have)
        if have_set != want:
            return [
                f"{filename} catchup-safe {tier_word} UNNEST list DRIFT — "
                f"file has {sorted(have_set)}, cadence.yaml-derived (catchup_safe AND {tier_word} tier) "
                f"wants {sorted(want)}"]
    return []


def class_map_errors(want, have, *, missing_from, mismatch_label, mismatch_ref, extra_in, extra_not_a):
    """Shared want/have `{id: class}` MISSING / mismatch / extra comparison used by check A
    (state.cadence_expected_today vs 12_cadence_monitor.sql) and check J (state.cadence_period_watch's
    routines CTE vs 24_cadence_period_watch.sql) — both independently re-derived this exact
    three-branch loop, differing only in message wording (2026-07-29 dedup).

    Every message fragment is a caller-supplied literal rather than something templated from a single
    filename: the two call sites' existing wording is not even internally consistent with itself
    (check A's own "extra" message says "12_*.sql" while its "missing"/"mismatch" messages say
    "12_cadence_monitor.sql") and these messages are load-bearing — CI and a BigQuery bridge parse
    them — so preserving them byte-for-byte matters more than a cleaner single-filename template."""
    errors = []
    for rid, cls in want.items():
        if rid not in have:
            errors.append(f"{rid}: monitor_class={cls} in cadence.yaml but MISSING from {missing_from}")
        elif have[rid] != cls:
            errors.append(f"{rid}: {mismatch_label} — cadence.yaml='{cls}' vs {mismatch_ref}='{have[rid]}'")
    for rid in have:
        if rid not in want:
            errors.append(f"{rid}: in {extra_in} but not a {extra_not_a}")
    return errors


def main():
    cad = load_cadence()
    headings = plan_headings()
    errors = []

    # ---- duplicate routine id in ops/cadence.yaml's routines list (silently collapsed by
    # load_cadence()'s dict comprehension otherwise -- see cadence_duplicate_ids()'s docstring) ----
    for rid in cadence_duplicate_ids():
        errors.append(f"ops/cadence.yaml: duplicate routine id '{rid}' — each routine id must "
                      f"appear exactly once")

    # ---- canonical maps from the SOURCE OF TRUTH (cadence.yaml + the plan) ----
    head_by_id, dup = {}, []
    for h in headings:
        rid = heading_to_id(h)
        if rid is None:
            errors.append(f"plan heading does not map to a routine id (bad format?): '{h}'")
            continue
        if rid in head_by_id:
            dup.append(rid)
        head_by_id[rid] = h
    for rid in dup:
        errors.append(f"duplicate Claude_Task_Plan.md heading for id {rid}")

    # check B must derive its expectation from the SAME shared template check F uses (lib/
    # routine_manifest.instruction_text) rather than re-literalizing the f-string here -- that literal
    # was the 4th independent copy the 2026-07-20 extraction was supposed to kill (codebase audit
    # 2026-07-26): edit instruction_text's wording and regenerate bigquery/15 via gen_routine_lists.py
    # --write, and this hardcoded copy would silently compute the OLD string, failing CI for every
    # routine with a diff that points at cadence.yaml/plan headings instead of the real culprit.
    want_catalog = {rid: instruction_text(h) for rid, h in head_by_id.items()}
    want_expected = {rid: r["monitor_class"] for rid, r in cad.items()
                     if r.get("monitor_class") in CALENDAR_CLASSES}

    # ---- validate monitor_class presence + vocabulary ----
    for rid, r in cad.items():
        mc = r.get("monitor_class")
        if mc is None:
            errors.append(f"{rid}: missing monitor_class in ops/cadence.yaml")
        elif mc not in ALLOWED_CLASSES:
            errors.append(f"{rid}: monitor_class '{mc}' not in {sorted(ALLOWED_CLASSES)}")

    # ---- depends_on references must be known routine ids (silent-drift guard) ----
    errors.extend(check_depends_on(cad))

    # ---- C. cadence.yaml id <-> plan heading 1:1 ----
    for rid in cad:
        if rid not in head_by_id:
            errors.append(f"{rid}: in ops/cadence.yaml but no matching Claude_Task_Plan.md heading")
    for rid in head_by_id:
        if rid not in cad:
            errors.append(f"{rid}: Claude_Task_Plan.md heading but no ops/cadence.yaml routine")

    # ---- A. state.cadence_expected_today (12_*.sql) == calendar-class routines in cadence.yaml ----
    have_expected = parse_expected_sql()
    if not have_expected:
        errors.append("could not parse any STRUCT(... AS schedule) rows from 12_cadence_monitor.sql")
    errors.extend(class_map_errors(
        want_expected, have_expected,
        missing_from="state.cadence_expected_today (12_cadence_monitor.sql)",
        mismatch_label="schedule class mismatch", mismatch_ref="12_cadence_monitor.sql",
        extra_in="state.cadence_expected_today (12_*.sql)",
        extra_not_a="calendar-class routine in cadence.yaml (queue_driven/unknown routines must NOT be listed)"))

    # ---- B. ops.routine_catalog (15_*.sql) == plan-heading-derived instruction ----
    have_catalog = parse_catalog_sql()
    if not have_catalog:
        errors.append("could not parse any catalog STRUCT rows from 15_routine_catalog.sql")
    for rid, instr in want_catalog.items():
        if rid not in have_catalog:
            errors.append(f"{rid}: has a plan heading but is MISSING from ops.routine_catalog (15_*.sql)")
        elif have_catalog[rid] != instr:
            errors.append(f"{rid}: routine_catalog instruction drift\n"
                          f"     plan-derived: {instr}\n"
                          f"     15_*.sql:     {have_catalog[rid]}")
    for rid in have_catalog:
        if rid not in want_catalog:
            errors.append(f"{rid}: in ops.routine_catalog (15_*.sql) but has no Claude_Task_Plan.md heading")

    # ---- D. cadence_watch deadline guard: cadence.yaml constant == bigquery/12 SQL TIME literal ----
    want_deadline = cadence_deadline_yaml()
    have_deadlines = parse_deadline_sql()
    deadline_ok = True
    if want_deadline is None:
        errors.append("ops/cadence.yaml: missing top-level 'cadence_watch_deadline_local' "
                      "(declares the state.cadence_watch deadline-guard time)")
        deadline_ok = False
    elif not (isinstance(want_deadline, str) and HHMM.match(want_deadline)):
        errors.append(f"ops/cadence.yaml: cadence_watch_deadline_local must be a quoted \"HH:MM\" string "
                      f"(got {want_deadline!r} — an UNquoted 21:00 is YAML base-60 = 1260; always quote it)")
        deadline_ok = False
    if not have_deadlines:
        errors.append("bigquery/12_cadence_monitor.sql: could not parse the DATETIME(e.today, TIME '..') "
                      "deadline-guard literal from state.cadence_watch (did the clause change shape?)")
        deadline_ok = False
    elif len(set(have_deadlines)) > 1:
        errors.append(f"bigquery/12_cadence_monitor.sql: multiple distinct deadline literals "
                      f"{sorted(set(have_deadlines))} in state.cadence_watch — expected exactly one")
        deadline_ok = False
    if deadline_ok and have_deadlines[0] != want_deadline:
        errors.append(f"cadence_watch deadline DRIFT — ops/cadence.yaml='{want_deadline}' vs "
                      f"bigquery/12_cadence_monitor.sql TIME='{have_deadlines[0]}'. Keep them in sync.")

    # ---- D (extended, 2026-08-06, bigquery/142 revert follow-up): the CANONICAL (highest-numbered)
    # bigquery/*.sql file CURRENTLY defining state.cadence_watch must ALSO agree with cadence.yaml.
    # bigquery/12 is itself long superseded (48 -> 113 -> 129 -> 142); the check above only ever compared
    # against that original, no-longer-deployed body, so a deadline change landed in a superseding file
    # (129's 21:00->21:45 autotune, then 142's revert back to 21:00) had NO CI guard tying it back to
    # cadence.yaml at all — the same registry-vs-body split class check_sq_version_registry.py exists to
    # catch for a heartbeat literal, applied here to this view. ----
    canon_deadlines, canon_number, canon_fn, canon_ambiguous = parse_canonical_deadline_sql()
    canon_deadline_ok = True
    if canon_ambiguous is not None:
        errors.append(
            f"AMBIGUOUS canonical file for state.cadence_watch — bigquery/{canon_number} is the "
            f"winning (highest) leading number, but {len(canon_ambiguous)} DIFFERENT files share it "
            f"and each defines `CREATE OR REPLACE VIEW state.cadence_watch`: "
            f"{', '.join('bigquery/' + fn for fn in canon_ambiguous)}. Check D's canonical-file "
            f"deadline guard cannot determine which is actually deployed — renumber one file so the "
            f"leading number is unique, or determine which definition is actually deployed and "
            f"delete/renumber the other.")
        canon_deadline_ok = False
    elif canon_fn is None:
        errors.append("could not find any bigquery/*.sql file defining "
                      "`CREATE OR REPLACE VIEW state.cadence_watch` at all — check D's canonical-file "
                      "deadline guard cannot run")
        canon_deadline_ok = False
    else:
        if not canon_deadlines:
            errors.append(f"bigquery/{canon_fn}: could not parse the DATETIME(e.today, TIME '..') "
                          f"deadline-guard literal from its state.cadence_watch definition (the "
                          f"highest-numbered file currently defining it — did the clause change shape?)")
            canon_deadline_ok = False
        elif len(set(canon_deadlines)) > 1:
            errors.append(f"bigquery/{canon_fn}: multiple distinct deadline literals "
                          f"{sorted(set(canon_deadlines))} in its state.cadence_watch definition — "
                          f"expected exactly one")
            canon_deadline_ok = False
    if deadline_ok and canon_deadline_ok and canon_fn is not None and canon_deadlines[0] != want_deadline:
        errors.append(f"cadence_watch deadline DRIFT (canonical file) — ops/cadence.yaml="
                      f"'{want_deadline}' vs bigquery/{canon_fn} (the highest-numbered file currently "
                      f"defining state.cadence_watch) TIME='{canon_deadlines[0]}'. Keep them in sync.")

    # ---- E. period_grace_days: cadence.yaml == bigquery/24_cadence_period_watch.sql ----
    want_grace = cadence_period_grace_yaml()
    have_grace = parse_period_grace_sql()
    if have_grace is not None:  # file present; if absent, this repo predates the feature — skip silently
        if want_grace is None:
            errors.append("ops/cadence.yaml: missing top-level 'period_grace_days' "
                          "(bigquery/24_cadence_period_watch.sql exists and needs a declared source of truth)")
        else:
            for cls in ("weekly_sun", "monthly_ftd", "quarterly_ftd", "annual_ftd"):
                y, s = want_grace.get(cls), have_grace.get(cls)
                if y is None:
                    errors.append(f"ops/cadence.yaml period_grace_days: missing '{cls}'")
                elif s is None:
                    errors.append(f"bigquery/24_cadence_period_watch.sql: could not parse a grace literal for '{cls}'")
                elif y != s:
                    errors.append(f"period_grace_days DRIFT for {cls} — ops/cadence.yaml={y} vs "
                                  f"bigquery/24_cadence_period_watch.sql={s}. Keep them in sync.")

    # ---- J. state.cadence_period_watch's `routines` CTE (24_*.sql) == period-class routines in
    # cadence.yaml (ARCH-3 Item 30b) — the GENERATED counterpart to check A, for the period-tier list. ----
    want_period_routines = {rid: r["monitor_class"] for rid, r in cad.items()
                             if r.get("monitor_class") in PERIOD_CLASSES}
    have_period_routines = parse_period_watch_routines_sql()
    if have_period_routines is not None:  # file present; absent = pre-feature checkout, skip silently
        if not have_period_routines:
            errors.append("could not parse any labelled STRUCT(... AS monitor_class) rows from "
                          "24_cadence_period_watch.sql's `routines` CTE")
        errors.extend(class_map_errors(
            want_period_routines, have_period_routines,
            missing_from="state.cadence_period_watch's routines CTE (24_cadence_period_watch.sql)",
            mismatch_label="period-watch monitor_class mismatch", mismatch_ref="24_cadence_period_watch.sql",
            extra_in="state.cadence_period_watch's routines CTE (24_*.sql)",
            extra_not_a="period-class routine in cadence.yaml"))

    # ---- K. catchup_safe: every cadence.yaml routine must declare the boolean, and bigquery/31/59's
    # hand-maintained UNNEST id lists must equal the corresponding {catchup_safe AND monitor_class in
    # <tier>} subset (ARCH-3 Item 30b — these two lists previously had ZERO drift protection). ----
    for rid, r in cad.items():
        if "catchup_safe" not in r:
            errors.append(f"{rid}: missing catchup_safe boolean in ops/cadence.yaml")
        elif not isinstance(r["catchup_safe"], bool):
            errors.append(f"{rid}: catchup_safe must be a boolean true/false (got {r['catchup_safe']!r})")

    errors.extend(catchup_list_errors(
        cad, CATCHUP_NOTIFY_SQL, "bigquery/31_catchup_notify.sql", "daily", DAILY_CLASSES))
    errors.extend(catchup_list_errors(
        cad, CATCHUP_AUTOFIRE_SQL, "bigquery/59_catchup_autofire.sql", "period", PERIOD_CLASSES))

    # ---- L. Claude_Task_Plan.md's ROUTINE INVENTORY table == cadence.yaml ids, and each row's
    # 'Cadence · Type' cell agrees with that routine's monitor_class (ARCH-3 Item 30b). ----
    have_inventory = parse_inventory_table(PLAN)
    if have_inventory is None:
        # 2026-07-29: unconditional hard error, not a skip. A prior version of this check tried to
        # tell "heading never introduced" (skip silently) apart from "heading reworded" (fail loud)
        # via a loose substring search — PROVEN DEFEATABLE the same day by a rewording that drops the
        # substring too (e.g. "# ROUTINE ROSTER & BIGQUERY RESPONSIBILITIES"), which made both
        # branches miss and let main() exit 0 silently, reproducing the exact bug the heuristic
        # existed to catch. The ROUTINE INVENTORY table is a mandatory section of Claude_Task_Plan.md
        # (itself not optional), so "the table can't be found" is a drift error in every case — there
        # is no legitimate skip case left to preserve.
        errors.append(
            f"Claude_Task_Plan.md: could not locate the exact heading '{INVENTORY_HEADING}' followed "
            f"by a parseable ROUTINE INVENTORY table — check L's drift guard cannot run. Either the "
            f"heading text was reworded (restore it exactly as shown above, or update "
            f"INVENTORY_HEADING in this script to match the new text), or the entire ROUTINE "
            f"INVENTORY section was deleted (restore it — the table is mandatory, so its absence is "
            f"itself a drift error, not a pre-feature-checkout case to skip).")
    else:  # heading present and table parsed — compare its rows against ops/cadence.yaml
        have_inventory_ids = {rid for rid, _cell in have_inventory}
        for rid in sorted(set(cad) - have_inventory_ids):
            errors.append(f"{rid}: in ops/cadence.yaml but missing a row in Claude_Task_Plan.md's "
                          f"ROUTINE INVENTORY table")
        for rid in sorted(have_inventory_ids - set(cad)):
            errors.append(f"{rid}: ROUTINE INVENTORY table row has no matching ops/cadence.yaml routine")
        for rid, cell in have_inventory:
            if rid not in cad:
                continue
            mc = cad[rid].get("monitor_class")
            token = cell.strip().split()[0] if cell.strip() else ""
            if rid in INVENTORY_FOOTNOTE_QUEUE_DRIVEN_IDS and token.rstrip("¹") == "Daily" and token.endswith("¹"):
                allowed = {"queue_driven"}
            else:
                allowed = INVENTORY_CADENCE_TOKEN_MAP.get(token)
            if allowed is None:
                errors.append(f"{rid}: ROUTINE INVENTORY 'Cadence · Type' cell first token '{token}' "
                              f"not recognized (Daily/Weekly/Monthly/Quarterly/Annual/Queue-driven)")
            elif mc not in allowed:
                errors.append(f"{rid}: ROUTINE INVENTORY cadence cell '{token}' implies monitor_class in "
                              f"{sorted(allowed)}, but ops/cadence.yaml has monitor_class='{mc}'")

    # ---- F. ops/triggers.json (if present) == the canonical generated map ----
    if os.path.exists(TRIGGERS_JSON):
        want_manifest = generate_triggers_manifest(head_by_id, cad)
        try:
            have_manifest = json.load(open(TRIGGERS_JSON, encoding="utf-8"))
        except (OSError, ValueError) as e:
            errors.append(f"ops/triggers.json: could not parse as JSON ({e})")
            have_manifest = None
        if have_manifest is not None and have_manifest != want_manifest:
            errors.append("ops/triggers.json is STALE — does not match the canonical map derived from "
                          "ops/cadence.yaml + Claude_Task_Plan.md headings. Regenerate with "
                          "`python scripts/print_routines.py --write` and commit the result "
                          "(it must be GENERATED, never hand-edited).")

    # ---- G. ops/trigger_ids.json (if present): unique trigger_ids, no entry for a routine no
    # longer in cadence.yaml (self-improvement audit, 2026-07-14 — this file had zero CI
    # validation despite being nearly identical in shape/purpose to ops/triggers.json). A cad
    # routine with NO entry yet is expected/transient (recorded once its live trigger is created)
    # and is a WARN, not a build failure. ----
    if os.path.exists(TRIGGER_IDS_JSON):
        try:
            trigger_ids_doc = json.load(open(TRIGGER_IDS_JSON, encoding="utf-8"))
        except (OSError, ValueError) as e:
            errors.append(f"ops/trigger_ids.json: could not parse as JSON ({e})")
            trigger_ids_doc = None
        if trigger_ids_doc is not None:
            have_ids = {k: v for k, v in trigger_ids_doc.items() if k != "_meta"}
            by_trigger = {}
            for rid, entry in have_ids.items():
                tid = (entry or {}).get("trigger_id")
                by_trigger.setdefault(tid, []).append(rid)
            for tid, rids in by_trigger.items():
                if tid and len(rids) > 1:
                    errors.append(f"ops/trigger_ids.json: trigger_id '{tid}' is shared by routines "
                                  f"{sorted(rids)} — duplicate/typo'd id would misdirect a live "
                                  f"RemoteTrigger call")
            stale = sorted(rid for rid in have_ids if rid not in cad)
            if stale:
                errors.append(f"ops/trigger_ids.json: entries for routine(s) no longer in "
                              f"ops/cadence.yaml: {stale} — remove the stale entry")
            missing = sorted(rid for rid in cad if rid not in have_ids)
            if missing:
                print(f"NOTE: ops/trigger_ids.json has no entry yet for {missing} (new routine — "
                      f"record its live trigger id once created via RemoteTrigger/Chrome; not a "
                      f"CI failure, per the file's own not-live-synced caveat).")

            # ---- I. expected_trigger: every routine WITH an ops/trigger_ids.json entry must carry a
            # well-formed `expected_trigger` in ops/cadence.yaml (trigger-config-drift audit, 2026-07-16,
            # ARCH-2/CC-5 merge). This is the structured, mechanically-diffable schedule Q4 step E and
            # OPS0 STEP 3 diff a live RemoteTrigger get() against, replacing the old free-text
            # WEB-UI TRIGGER AUDIT comment block as the enforced source of truth. A routine with NO
            # trigger_ids.json entry yet (OPS0, until its live trigger is created) is a NOTE only,
            # mirroring the NOTE just above — not a build failure. ----
            EXPECTED_TRIGGER_RECURRENCE = {"daily", "weekly", "custom_cron"}
            for rid in sorted(cad):
                et = cad[rid].get("expected_trigger")
                if rid not in have_ids:
                    if et is None:
                        print(f"NOTE: {rid} has no expected_trigger yet (no live trigger id recorded "
                              f"either — expected until ops/trigger_ids.json gets an entry for it).")
                    continue
                if et is None:
                    errors.append(f"{rid}: has an ops/trigger_ids.json entry but no 'expected_trigger' "
                                  f"in ops/cadence.yaml (structured schedule required for the "
                                  f"RemoteTrigger-diff self-heal sweep — Q4 step E / OPS0 STEP 3)")
                    continue
                rec = et.get("recurrence")
                if rec not in EXPECTED_TRIGGER_RECURRENCE:
                    errors.append(f"{rid}: expected_trigger.recurrence={rec!r} not in "
                                  f"{sorted(EXPECTED_TRIGGER_RECURRENCE)}")
                    continue
                if "enabled" not in et:
                    errors.append(f"{rid}: expected_trigger missing 'enabled'")
                if rec in ("daily", "weekly"):
                    tl = et.get("time_local")
                    if not (isinstance(tl, str) and HHMM.match(tl)):
                        errors.append(f"{rid}: expected_trigger.time_local must be a quoted \"HH:MM\" "
                                      f"string for recurrence={rec} (got {tl!r} — an unquoted HH:MM is "
                                      f"YAML base-60, same caveat as cadence_watch_deadline_local)")
                elif rec == "custom_cron":
                    cu = et.get("cron_utc")
                    if not (isinstance(cu, str) and cu.strip()):
                        errors.append(f"{rid}: expected_trigger.cron_utc must be a non-empty string "
                                      f"(TO_POPULATE bootstrap placeholder, or an observed cron once a "
                                      f"sweep has populated it) for recurrence=custom_cron")

    # ---- H. auto-merge-claude.yml's RUNBOOK §38 marker-write routine_re must accept every
    # cadence.yaml id (self-improvement audit, 2026-07-14) — this hand-typed alternation is a
    # second copy of the routine-id set already carried by ops/cadence.yaml, with no guard: a
    # routine added to cadence.yaml but not to this regex has its commits silently skipped by the
    # §38 marker-write self-heal, with no CI signal. Only checks the cadence-ids-subset-of-regex
    # direction (under-inclusive/silent-skip) — the regex being a superset is harmless. ----
    # The literal moved into the sourced helper on 2026-07-29. Look in BOTH locations and validate
    # EVERY copy found (not first-match-wins): if the allowlist is ever duplicated across the helper
    # and the workflow, a stale second copy must fail loudly rather than hide behind a complete one.
    # Read the module globals at call time so tests can monkeypatch either path.
    allowlist_paths = [p for p in (AUTO_MERGE_DECISION_SH, AUTO_MERGE_YML) if os.path.exists(p)]
    if allowlist_paths:
        found = [(p, AUTO_MERGE_ROUTINE_RE.search(read_text(p)))
                 for p in allowlist_paths]
        found = [(p, m) for p, m in found if m is not None]
        if not found:
            errors.append("could not find the RUNBOOK §38 marker-write routine allowlist literal in "
                          "scripts/auto_merge_decision.sh or .github/workflows/auto-merge-claude.yml "
                          "— its shape may have changed; update AUTO_MERGE_ROUTINE_RE / "
                          "AUTO_MERGE_DECISION_SH / AUTO_MERGE_YML in this script to match")
        for _p, m in found:
            _rel = os.path.relpath(_p, ROOT)
            routine_re_pat = re.compile(f"^(?:{m.group(1)})$")
            for rid in cad:
                if not routine_re_pat.fullmatch(rid):
                    errors.append(f"{rid}: in ops/cadence.yaml but NOT matched by {_rel}'s "
                                  f"routine_re — RUNBOOK §38 marker-write will silently skip this "
                                  f"routine's commits (add it to the routine_re alternation)")
    else:
        # Both candidate locations missing is not "nothing to check", it is check H having no signal
        # at all — the same silent-no-op shape as the substring-gate bug check M had (2026-08-08 audit
        # finding). Neither file existing at once is implausible today, but a future rename/move of
        # BOTH without updating this script must not read as a clean CI run.
        errors.append("could not find the RUNBOOK §38 marker-write routine allowlist source — neither "
                      f"{os.path.relpath(AUTO_MERGE_DECISION_SH, ROOT)} nor "
                      f"{os.path.relpath(AUTO_MERGE_YML, ROOT)} exists, so check H validated nothing; "
                      "restore one of these files or update AUTO_MERGE_DECISION_SH / AUTO_MERGE_YML "
                      "in this script to match their new location")

    # ---- M. EVENING-slot daily SAME-DAY guard copies carry the noon-threshold clause (H1). ----
    # Used to be gated on the "SAME-DAY DOUBLE-RUN GUARD" sentinel being present at all, on the theory
    # that this only ever skips a minimal test fixture / pre-feature checkout — but a bare substring
    # gate fails open on ANY loss of that heading (a rename, a rewrite that drops the sentinel word),
    # silently disarming the whole check with no CI signal, not just the fixture case it was written
    # for (2026-08-08 audit finding). The inner loop below already errors loudly, per routine, when
    # GUARD_QUERY_RE[rid] finds no match — there is no reason total absence of the sentinel should be
    # quieter than that. Run unconditionally: a plan with zero SAME-DAY DOUBLE-RUN GUARD text now fails
    # loudly (one error per EVENING_DAILY_GUARD_IDS routine) instead of passing vacuously. Test
    # fixtures that don't care about check M must now carry valid guard text too (see
    # tests/test_cadence_consistency.py's _write_check_fixture / _AR_ATT_PLAN).
    plan_txt = open(PLAN, encoding="utf-8").read()
    for rid in EVENING_DAILY_GUARD_IDS:
        matches = list(GUARD_QUERY_RE[rid].finditer(plan_txt))
        if not matches:
            errors.append(f"{rid}: could not find its SAME-DAY DOUBLE-RUN GUARD `ops.run_log` "
                          f"COUNT(*) query in Claude_Task_Plan.md — check M's H1 noon-threshold guard "
                          f"is DISARMED for this routine (did the guard query change shape?)")
            continue
        for m in matches:
            if not GUARD_NOON_CLAUSE_RE.search(m.group("after")):
                errors.append(
                    f"{rid}: SAME-DAY DOUBLE-RUN GUARD copy is MISSING the noon-threshold clause "
                    f"(H1) — an EVENING-slot daily routine (slot >= 16:00 MT) must count only "
                    f"completions in the real evening window: append "
                    f"`AND DATETIME(log_ts,'America/Denver') >= DATETIME(<today, America/Denver>, "
                    f"TIME '12:00:00')` to its `status='completed'` COUNT(*) query, so a post-midnight "
                    f"prior-day run mis-stamped onto today by bigquery/12's midnight-crossing grace "
                    f"cannot cancel the genuine evening run (see the shared Observability guard's "
                    f"CYCLE-AWARE VARIANT).")

    # ---- N. model of record: cadence.yaml routine_model == every mirror site ----
    model_errs, model_of_record = check_model_of_record()
    errors.extend(model_errs)

    # ---- O. state.stalled_runs' `cls` CTE routine list == ops/cadence.yaml's routine ids, BOTH
    # directions (see the comment above STALLED_RUNS_VIEW_DDL for the full WHY -- this is the same
    # class of gap that let OPS0/OPS1/OPS2 hang undetected for weeks until bigquery/148). ----
    cls_ids, cls_number, cls_fn, cls_ambiguous = parse_stalled_runs_cls_ids()
    if cls_ambiguous is not None:
        errors.append(
            f"AMBIGUOUS canonical file for state.stalled_runs — bigquery/{cls_number} is the "
            f"winning (highest) leading number, but {len(cls_ambiguous)} DIFFERENT files share it "
            f"and each defines `CREATE OR REPLACE VIEW state.stalled_runs`: "
            f"{', '.join('bigquery/' + fn for fn in cls_ambiguous)}. Check O's cls-list drift guard "
            f"cannot determine which is actually deployed — renumber one file so the leading number "
            f"is unique, or determine which definition is actually deployed and delete/renumber the "
            f"other.")
    elif cls_fn is None:
        errors.append("could not find any bigquery/*.sql file defining "
                      "`CREATE OR REPLACE VIEW state.stalled_runs` at all — check O's cls-list drift "
                      "guard cannot run")
    elif not cls_ids:
        errors.append(f"bigquery/{cls_fn}: could not parse any routine id out of state.stalled_runs' "
                      f"`cls` CTE UNNEST([...]) STRUCT list — check O's cls-list drift guard is "
                      f"DISARMED (regex rot? e.g. a reformat of the STRUCT(...) rows, or of the "
                      f"`cls AS (... UNNEST([...]) ...)` shape itself). Restore a parseable `cls` CTE.")
    else:
        cls_set, cad_set = set(cls_ids), set(cad)
        for rid in sorted(cad_set - cls_set):
            errors.append(f"{rid}: in ops/cadence.yaml but MISSING from bigquery/{cls_fn}'s "
                          f"state.stalled_runs `cls` CTE — this routine can NEVER be flagged "
                          f"routine_stalled no matter how long it hangs (the `JOIN cls c USING "
                          f"(routine)` INNER join drops it before the terminal-row anti-join or "
                          f"elapsed-hours threshold ever run — this is exactly the OPS0/OPS1/OPS2 "
                          f"gap bigquery/148 fixed). Add a STRUCT('{rid}', <min_stale_hours>) entry.")
        for rid in sorted(cls_set - cad_set):
            errors.append(f"{rid}: in bigquery/{cls_fn}'s state.stalled_runs `cls` CTE but not a "
                          f"routine id in ops/cadence.yaml — stale entry for a retired/renamed "
                          f"routine, remove it.")

    # ---- report ----
    if errors:
        print("CADENCE CONSISTENCY: FAIL\n")
        for e in errors:
            print(" - " + e)
        print("\nFix ops/cadence.yaml (monitor_class) / Claude_Task_Plan.md headings and the matching "
              "bigquery/12_cadence_monitor.sql + bigquery/15_routine_catalog.sql so all three agree, "
              "then re-run. (See ops/cadence.yaml header + scripts/print_routines.py.)")
        return 1

    extra = ""
    if have_grace is not None:
        extra += " period_grace_days matches 24_cadence_period_watch.sql."
    if os.path.exists(TRIGGERS_JSON):
        extra += " ops/triggers.json is current."
    if model_of_record:
        extra += f" routine_model {model_of_record} matches all mirror sites."
    if cls_fn is not None:
        extra += f" state.stalled_runs cls list (bigquery/{cls_fn}) matches all {len(cad)} routine ids."
    canon_note = (f" and bigquery/{canon_fn} (canonical)" if canon_fn is not None else "")
    print(f"CADENCE CONSISTENCY: OK — {len(cad)} routines; "
          f"{len(want_expected)} calendar-class match state.cadence_expected_today; "
          f"{len(have_catalog)} catalog entries match the plan headings; "
          f"cadence_watch deadline {want_deadline} matches 12_cadence_monitor.sql (superseded reference)"
          f"{canon_note}.{extra}")
    return 0


